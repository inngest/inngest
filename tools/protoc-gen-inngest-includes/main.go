package main

import (
	"fmt"
	"sort"
	"strings"
	"unicode"

	openapiv2 "github.com/grpc-ecosystem/grpc-gateway/v2/protoc-gen-openapiv2/options"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	generatedFilename = "pkg/api/v2/include_selectors.gen.go"
	generatedPackage  = protogen.GoImportPath("github.com/inngest/inngest/pkg/api/v2")
	endpointPackage   = protogen.GoImportPath("github.com/inngest/inngest/pkg/api/v2/apiv2endpoint")
)

type selectorSpec struct {
	method   string
	typeName string
	values   []string
	aliases  map[string]string
}

func main() {
	protogen.Options{}.Run(generate)
}

func generate(plugin *protogen.Plugin) error {
	plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

	var specs []selectorSpec
	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}
		for _, service := range file.Services {
			for _, method := range service.Methods {
				values := includeValues(method.Desc)
				if len(values) == 0 {
					continue
				}
				spec, err := newSelectorSpec(
					string(method.Desc.Name()),
					includeTypeName(method.Desc),
					values,
				)
				if err != nil {
					return err
				}
				specs = append(specs, spec)
			}
		}
	}
	if len(specs) == 0 {
		return nil
	}

	sort.Slice(specs, func(i, j int) bool { return specs[i].method < specs[j].method })
	g := plugin.NewGeneratedFile(generatedFilename, generatedPackage)
	g.P("// Code generated by protoc-gen-inngest-includes. DO NOT EDIT.")
	g.P()
	g.P("package apiv2")
	g.P()
	return emitSelectors(g, specs)
}

func includeValues(method protoreflect.MethodDescriptor) []string {
	include := method.Input().Fields().ByJSONName("include")
	if include == nil || !include.IsList() || include.Kind() != protoreflect.StringKind {
		return nil
	}
	opts := include.Options()
	if !proto.HasExtension(opts, openapiv2.E_Openapiv2Field) {
		return nil
	}
	schema, _ := proto.GetExtension(opts, openapiv2.E_Openapiv2Field).(*openapiv2.JSONSchema)
	if schema == nil {
		return nil
	}
	return schema.GetEnum()
}

func includeTypeName(method protoreflect.MethodDescriptor) string {
	return string(method.Name()) + "Include"
}

func newSelectorSpec(name, typeName string, values []string) (selectorSpec, error) {
	spec := selectorSpec{
		method:   name,
		typeName: typeName,
		values:   append([]string(nil), values...),
		aliases:  map[string]string{},
	}
	for _, canonical := range values {
		if !isLowerCamel(canonical) {
			return selectorSpec{}, fmt.Errorf("include value %q for %s must be lowerCamelCase", canonical, name)
		}
		if err := spec.add(canonical, canonical); err != nil {
			return selectorSpec{}, err
		}
		if err := spec.add(snakeCase(canonical), canonical); err != nil {
			return selectorSpec{}, err
		}
	}
	return spec, nil
}

func (s selectorSpec) add(alias, canonical string) error {
	if existing, ok := s.aliases[alias]; ok && existing != canonical {
		return fmt.Errorf("include value %q is ambiguous for %s", alias, s.method)
	}
	s.aliases[alias] = canonical
	return nil
}

func isLowerCamel(value string) bool {
	for i, r := range value {
		if i == 0 && (r < 'a' || r > 'z') {
			return false
		}
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			return false
		}
	}
	return value != ""
}

func snakeCase(value string) string {
	runes := []rune(value)
	var result strings.Builder
	for i, r := range runes {
		if unicode.IsUpper(r) && i > 0 &&
			(unicode.IsLower(runes[i-1]) || unicode.IsDigit(runes[i-1]) ||
				i+1 < len(runes) && unicode.IsLower(runes[i+1])) {
			result.WriteByte('_')
		}
		result.WriteRune(unicode.ToLower(r))
	}
	return result.String()
}

func emitSelectors(g *protogen.GeneratedFile, specs []selectorSpec) error {
	types := map[string]map[string]string{}
	for _, spec := range specs {
		values, ok := types[spec.typeName]
		if !ok {
			values = map[string]string{}
			types[spec.typeName] = values
		}
		for _, value := range spec.values {
			name := goName(value)
			if existing, ok := values[name]; ok && existing != value {
				return fmt.Errorf("include values %q and %q generate the same Go name", existing, value)
			}
			values[name] = value
		}
	}

	typeNames := make([]string, 0, len(types))
	for typeName := range types {
		typeNames = append(typeNames, typeName)
	}
	sort.Strings(typeNames)
	for _, typeName := range typeNames {
		g.P("// ", typeName, " is an internal expansion selected by generated API parsers.")
		g.P("type ", typeName, " uint8")
		g.P()
		values := types[typeName]
		names := make([]string, 0, len(values))
		for name := range values {
			names = append(names, name)
		}
		sort.Strings(names)
		g.P("const (")
		for i, name := range names {
			if i == 0 {
				g.P(typeName, name, " ", typeName, " = iota + 1")
				continue
			}
			g.P(typeName, name)
		}
		g.P(")")
		g.P()
	}

	for _, spec := range specs {
		g.P()
		g.P("var ", lowerFirst(spec.method), "IncludeSelector = ", g.QualifiedGoIdent(endpointPackage.Ident("NewIncludeSelector")), "(map[string]", spec.typeName, "{")
		aliases := make([]string, 0, len(spec.aliases))
		for alias := range spec.aliases {
			aliases = append(aliases, alias)
		}
		sort.Strings(aliases)
		for _, alias := range aliases {
			g.P(fmt.Sprintf("%q: %s%s,", alias, spec.typeName, goName(spec.aliases[alias])))
		}
		g.P("})")
		g.P()
		g.P("// Parse", spec.typeName, " parses a canonical selector or its snake_case compatibility alias.")
		g.P("func Parse", spec.typeName, "(value string) (", spec.typeName, ", error) {")
		g.P("return ", lowerFirst(spec.method), "IncludeSelector.Parse(value)")
		g.P("}")
		g.P()
	}
	return nil
}

func goName(value string) string {
	var result strings.Builder
	upper := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		result.WriteRune(r)
	}
	return result.String()
}

func lowerFirst(value string) string {
	if value == "" {
		return ""
	}
	runes := []rune(value)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}
